import { useEffect, useState } from 'react'
import { getEvalResults } from '../api.js'
import './Results.css'

function MetricBar({ label, intentlens, baseline }) {
  const il = intentlens ?? null
  const bl = baseline ?? null
  if (il === null && bl === null) return null
  const maxVal = Math.max(il ?? 0, bl ?? 0, 0.01)

  return (
    <div className="results-metric">
      <div className="results-metric__label">{label}</div>
      <div className="results-metric__bars">
        <div className="results-metric__bar-wrap" title={`IntentLens: ${il ?? 'N/A'}`}>
          <div className="results-metric__bar-track">
            <div
              className="results-metric__bar results-metric__bar--il"
              style={{ width: il !== null ? `${(il / maxVal) * 100}%` : '0%' }}
              role="progressbar"
              aria-valuenow={il ? Math.round(il * 100) : 0}
              aria-valuemin={0}
              aria-valuemax={100}
              aria-label={`IntentLens ${label}: ${il !== null ? Math.round(il * 100) + '%' : 'N/A'}`}
            />
          </div>
          <span className="results-metric__val results-metric__val--il">
            {il !== null ? Math.round(il * 100) + '%' : '—'}
          </span>
          <span className="results-metric__syst">IntentLens</span>
        </div>
        <div className="results-metric__bar-wrap" title={`Baseline: ${bl ?? 'N/A'}`}>
          <div className="results-metric__bar-track">
            <div
              className="results-metric__bar results-metric__bar--bl"
              style={{ width: bl !== null ? `${(bl / maxVal) * 100}%` : '0%' }}
              role="progressbar"
              aria-valuenow={bl ? Math.round(bl * 100) : 0}
              aria-valuemin={0}
              aria-valuemax={100}
              aria-label={`Baseline ${label}: ${bl !== null ? Math.round(bl * 100) + '%' : 'N/A'}`}
            />
          </div>
          <span className="results-metric__val results-metric__val--bl">
            {bl !== null ? Math.round(bl * 100) + '%' : '—'}
          </span>
          <span className="results-metric__syst">Vector-RAG baseline</span>
        </div>
      </div>
    </div>
  )
}

function MetricTable({ data, title }) {
  if (!data || Object.keys(data).length === 0) return null
  return (
    <div className="results-table-wrap">
      <h3 className="results-table__title">{title}</h3>
      <table className="results-table">
        <thead>
          <tr>
            <th>Metric</th>
            <th>Vector-RAG baseline</th>
            <th>IntentLens</th>
          </tr>
        </thead>
        <tbody>
          {Object.entries(data).map(([metric, vals]) => {
            const il = vals?.intentlens ?? null
            const bl = vals?.baseline ?? null
            const fmtVal = v => (v === null || v === undefined) ? '—' : (typeof v === 'number' ? (v < 1 ? Math.round(v * 100) + '%' : v) : v)
            const ilWins = il !== null && bl !== null && il > bl
            const blWins = bl !== null && il !== null && bl > il
            return (
              <tr key={metric}>
                <td>{metric.replace(/_/g, ' ')}</td>
                <td className={blWins ? 'results-table__win' : ''}>{fmtVal(bl)}</td>
                <td className={ilWins ? 'results-table__win' : ''}>{fmtVal(il)}</td>
              </tr>
            )
          })}
        </tbody>
      </table>
    </div>
  )
}

function EmptyState() {
  return (
    <div className="results-empty">
      <h2 className="results-empty__heading">No evaluation results yet</h2>
      <p className="results-empty__body">
        Results are generated by running the evaluation harness against the loaded graph.
        The file <code>docs/EVALUATION_RESULTS.md</code> does not exist yet.
      </p>
      <div className="results-empty__cmd">
        <code>make eval</code>
      </div>
      <p className="results-empty__note">
        This compares IntentLens against a vector-only RAG baseline on a gold set of answerable,
        unanswerable, and supersession questions.
      </p>
    </div>
  )
}

export default function Results() {
  const [data, setData]     = useState(undefined)  // undefined = loading
  const [error, setError]   = useState('')

  useEffect(() => {
    getEvalResults()
      .then(d => setData(d))
      .catch(e => setError(e.message))
  }, [])

  const loading = data === undefined && !error

  return (
    <main id="main" className="results-page">
      <div className="results-hero container">
        <h1 className="results-hero__title">Evaluation results</h1>
        <p className="results-hero__body">
          IntentLens vs a vector-only RAG baseline on a gold set of 45 questions: 30 answerable, 10 unanswerable, 5 supersession cases.
        </p>
      </div>

      <div className="container">
        {loading && (
          <div className="results-loading" aria-live="polite">
            <p>Loading results…</p>
          </div>
        )}
        {error && (
          <div className="results-error" role="alert">
            <p>Failed to load results: {error}</p>
          </div>
        )}
        {data === null && <EmptyState />}
        {data && (
          <>
            {data.calibration && (
              <section className="results-section" aria-labelledby="calibration-heading">
                <h2 id="calibration-heading" className="results-section__title">Calibration check</h2>
                <div className="results-calibration">
                  <div className="results-calibration__item">
                    <span className="results-calibration__label">Mean confidence — correct answers</span>
                    <span className="results-calibration__val results-calibration__val--good">
                      {data.calibration.mean_conf_correct}
                    </span>
                  </div>
                  <div className="results-calibration__item">
                    <span className="results-calibration__label">Mean confidence — incorrect answers</span>
                    <span className="results-calibration__val">
                      {data.calibration.mean_conf_incorrect}
                    </span>
                  </div>
                  {data.calibration.mean_conf_correct && data.calibration.mean_conf_incorrect && (
                    <div className="results-calibration__item">
                      <span className="results-calibration__label">Gap</span>
                      <span className="results-calibration__val results-calibration__val--good">
                        {(data.calibration.mean_conf_correct - data.calibration.mean_conf_incorrect).toFixed(3)}
                      </span>
                    </div>
                  )}
                </div>
                <p className="results-note">
                  A positive gap means the confidence model is discriminative — higher confidence on answers that are actually correct.
                </p>
              </section>
            )}

            {data.dev && (
              <section className="results-section" aria-labelledby="dev-heading">
                <h2 id="dev-heading" className="results-section__title">Dev split — key metrics</h2>
                <div className="results-bars">
                  {[
                    { key: 'answer_accuracy',       label: 'Answer accuracy' },
                    { key: 'supersession_accuracy', label: 'Supersession accuracy' },
                    { key: 'refusal_correctness',   label: 'Refusal correctness' },
                  ].map(({ key, label }) => {
                    const vals = data.dev[key]
                    return (
                      <MetricBar
                        key={key}
                        label={label}
                        intentlens={vals?.intentlens ?? null}
                        baseline={vals?.baseline ?? null}
                      />
                    )
                  })}
                </div>
                <MetricTable data={data.dev} title="All dev metrics" />
              </section>
            )}

            {data.held_out && (
              <section className="results-section" aria-labelledby="held-heading">
                <h2 id="held-heading" className="results-section__title">Held-out split</h2>
                <p className="results-note">
                  The held-out split was not used during tuning. These numbers reflect generalisation performance.
                </p>
                <MetricTable data={data.held_out} title="Held-out metrics" />
              </section>
            )}

            <section className="results-section" aria-labelledby="notes-heading">
              <h2 id="notes-heading" className="results-section__title">How we measured</h2>
              <div className="results-methodology">
                <div className="results-method-block">
                  <h3 className="results-method-block__title">Gold set</h3>
                  <p>45 questions in <code>eval/gold_questions.json</code>, split into dev (28) and held-out (17). Ground truth is drawn only from authoritative sources: Redis changelog, release notes, commit messages, and well-known design threads. Each question records its source URL in <code>source_note</code>.</p>
                  <ul className="results-method-types">
                    <li><span className="results-method-type results-method-type--answerable">30 answerable</span> — question has a decision in the graph; expected answer keywords recorded</li>
                    <li><span className="results-method-type results-method-type--unanswerable">10 unanswerable</span> — question is outside the subsystem or predates the loaded graph; system must refuse</li>
                    <li><span className="results-method-type results-method-type--supersession">5 supersession</span> — best-matching decision was superseded; system must surface the replacement and show a banner</li>
                  </ul>
                </div>

                <div className="results-method-block">
                  <h3 className="results-method-block__title">Systems compared</h3>
                  <p>Both systems use the same loaded graph, the same LLM (Nemotron 3 Ultra via Nebius Token Factory), and the same gold questions.</p>
                  <dl className="results-method-systems">
                    <div>
                      <dt>Vector-RAG baseline</dt>
                      <dd>Top-5 comments by embedding similarity → LLM summary. No graph traversal. No supersession check. Never refuses. Implemented in <code>eval/baseline_rag.py</code>.</dd>
                    </div>
                    <div>
                      <dt>IntentLens</dt>
                      <dd>Entity linking → GOVERNS traversal → evidence pack → grounded generation with citation verification → supersession check → 5-factor confidence → refusal below threshold.</dd>
                    </div>
                  </dl>
                </div>

                <div className="results-method-block">
                  <h3 className="results-method-block__title">Metrics</h3>
                  <dl className="results-method-metrics">
                    {[
                      ['Answer accuracy',       'Fraction of answerable questions where the answer contains ≥50% of the expected keywords.'],
                      ['Supersession accuracy', 'Fraction of supersession questions where: keywords match, superseded keywords absent, superseded_notice present when expected.'],
                      ['Refusal correctness',   'Fraction of unanswerable questions where the system refused. Baseline is always 0% — it never refuses.'],
                      ['Citation precision',    'Precision of cited evidence IDs against the gold evidence set. Null when gold_evidence_ids is empty.'],
                      ['Calibration gap',       'Mean confidence on correct answers minus mean confidence on incorrect answers. Positive = discriminative; 0 = random; negative = inverted.'],
                      ['p95 latency',           '95th-percentile response time in milliseconds across all gold questions.'],
                    ].map(([name, desc]) => (
                      <div key={name}>
                        <dt>{name}</dt>
                        <dd>{desc}</dd>
                      </div>
                    ))}
                  </dl>
                </div>

                <div className="results-method-block results-method-block--rules">
                  <h3 className="results-method-block__title">Honest-reporting rules</h3>
                  <ul className="results-method-rules">
                    <li>The weights and thresholds were tuned only on the dev split. The held-out split was not seen during tuning.</li>
                    <li>Failures are reported without softening. If a metric is worse than the baseline, it is shown worse.</li>
                    <li>The keyword-matching scorer is a lower bound. Some correct answers may not use the exact expected keywords. An LLM judge pass would give a higher but less reproducible number; we report the keyword number as the primary metric.</li>
                    <li>The held-out accuracy is lower because held-out questions target PR-mined decisions not yet in the graph (no GitHub token loaded). This is a data-coverage issue, not a model issue, and is noted as such.</li>
                  </ul>
                </div>
              </div>
            </section>
          </>
        )}
      </div>
    </main>
  )
}
